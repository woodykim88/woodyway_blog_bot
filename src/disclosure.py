"""글이 AI로 쓰였다고 밝히는 문장을 발행 전에 지운다 (9/27·9/30 운영자 결정: 필자가 직접 쓴 글처럼 보여야 한다).

"AI가 만든 이미지 구별법"처럼 AI를 다루는 정상 문장은 남기고, 이 글 자체의 작성 방식을 밝히는 문장만 지운다.
글을 탈락시키지 않고 그 문장만 빼므로 발행은 건너뛰지 않는다.
"""
from __future__ import annotations

import re

from src.models import PostDraft

_TOOL = r'(?:AI|인공지능|생성형\s*AI|챗\s*GPT|ChatGPT|GPT|Gemini|제미나이|Claude|클로드)'
_SELF = r'(?:이|본)\s*(?:글|포스팅|포스트)'

_PATTERNS = (
    # 이 글은 AI의 도움을 받아 작성했습니다 / 본 포스팅은 ChatGPT로 정리한 내용입니다
    re.compile(rf'{_SELF}\S*\s.{{0,30}}{_TOOL}.{{0,20}}(?:작성|정리|생성|제작|도움)', re.S),
    # AI가 작성한 글입니다 / AI로 생성된 콘텐츠입니다
    re.compile(rf'{_TOOL}\s*(?:가|이|로|으로|를\s*활용해|의\s*도움으로)\s*(?:작성|생성|제작)(?:한|된)\s*(?:글|포스팅|콘텐츠|컨텐츠|내용)\s*입니다'),
    # (Generated by AI) / written by AI / created with ChatGPT
    re.compile(rf'(?:generated|written|created|produced)\s+(?:by|with|using)\s+{_TOOL}', re.I),
)

# 이미지 설명(image_alt)에서만: (AI 생성 이미지). 본문의 "AI로 생성한 이미지 구별법"은 정상 내용이라 건드리지 않는다.
_IMAGE_PATTERN = re.compile(rf'{_TOOL}\s*(?:로\s*)?(?:생성|제작)(?:된|한)?\s*이미지')

# 괄호 덩어리 / 문장(끝 문장부호까지) / 남는 문장부호·괄호로 자른다. 세 가지가 글자를 빠짐없이 덮는다.
_SENTENCE = re.compile(r'\([^()]*\)|[^.!?。()]+[.!?。]*|[.!?。()]+')


def is_ai_disclosure(text: str, image: bool = False) -> bool:
    return any(p.search(text) for p in _PATTERNS) or (image and bool(_IMAGE_PATTERN.search(text)))


def _clean_paragraph(paragraph: str, image: bool) -> str:
    pieces = [m.group(0) for m in _SENTENCE.finditer(paragraph)]
    kept = [p for p in pieces if not is_ai_disclosure(p, image)]
    return re.sub(r'\s+', ' ', ''.join(kept)).strip() if len(kept) != len(pieces) else paragraph


def clean_text(text: str, image: bool = False) -> str:
    """문단 구분(빈 줄)은 지키면서 AI 작성 고지 문장만 뺍니다. 비게 된 문단은 없앱니다."""
    if not is_ai_disclosure(text, image):
        return text
    paragraphs = [_clean_paragraph(p, image) for p in text.split('\n\n')]
    return '\n\n'.join(p for p in paragraphs if p)


def strip_ai_disclosure(draft: PostDraft) -> PostDraft:
    """초안의 모든 문장 필드에서 AI 작성 고지 문장을 지운 새 초안을 돌려줍니다."""
    sections = [s.model_copy(update={'body': clean_text(s.body), 'tip': clean_text(s.tip)}) for s in draft.sections]
    glossary = [g.model_copy(update={'meaning': clean_text(g.meaning)}) for g in draft.glossary]
    return draft.model_copy(update={
        'title': clean_text(draft.title),
        'hook': clean_text(draft.hook),
        'key_points': [c for c in (clean_text(p) for p in draft.key_points) if c],
        'sections': sections,
        'why_it_matters': clean_text(draft.why_it_matters),
        'action_items': [c for c in (clean_text(a) for a in draft.action_items) if c],
        'glossary': glossary,
        'meta_description': clean_text(draft.meta_description),
        'image_alt': clean_text(draft.image_alt, image=True),
    })
